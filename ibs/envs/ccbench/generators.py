class ChannelGenerator:
    def __init__(
        self,
        channel_name: str,
        spec: Optional[Mapping[str, Any]] = None,
        replay: Optional[pd.Series] = None,
        rng: Optional[np.random.Generator] = None,
    ):
        """
        Provide basis class for channel generator class hierarchy.

        Args:
            channel_name: name of the channel this generator is used for
            spec: contains configuration parameters for channel generator instance, usually taken from yaml
                configuration file
            replay: optional series with values to be returned instead of generated ones (for matching timesteps)
            rng: random number generator used for all random draws of this generator; if None, a new, unseeded
                generator is created. Pass a seeded generator (e.g. the environment's `np_random`) for reproducible
                data.
        """
        self.channel_name = channel_name
        self.spec: Dict[str, Any] = dict(spec) if spec is not None else {}
        self.replay = replay
        self.rng = rng if rng is not None else np.random.default_rng()

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        """
        Computes and returns next channel value, potentially using history of this and other channels, and the current
        intermediate value computed by channel generator instances before the current one in the `type` list of the
        spec.

        Args:
            timestep: the time for the currently generated sample; could be used to check availability of current
                sample in series for other channels in `history`.
            history: contains series with the history of all previously generated channel data. Some of these contain
                a value for the current timestep, others may not contain it yet, because they are computed after the
                current generator value.
            cur_val: the value for this channel and for the current time step, generated by the generator just before
                the current one in the `spec["type"]` list. If this is the first generator for the channel, this will
                be `None`.

        Returns:
            The generated channel value
        """
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        return cur_val if cur_val is not None else 0.0

    def info_str(self, verbosity=1):
        """Return a short string representing the type of generator (class) and most import configuration parameters."""
        if verbosity <= 1:
            return short_class_name(self.__class__.__name__)
        return f"{self.__class__.__name__}"


class control_from_actions(ChannelGenerator):
    """
    Using a _control_ channel initial value and the configured `assoc_action_channel` _action_ channel, sum up all
    past values of the latter (actions), and add them to the initial control channel value, to obtain the timeseries
    of the corresponding control channel.

    In the `process_spec` structure of the config file, each of the parameters below must be prefixed with a "cfa_",
    to allow same argument names for different generators.

    Args:
        init: initialization value for fist observation, before and previous values and actions have been
            generated/observed. This can also be a two-element-tuple/list, in which case the initialization value
            will be randomly generated between the interval specified, for each episode.
    """

    def __init__(self, init: Optional[float] = None, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.last_val = init if init is not None else self.spec.get("cfa_init", 1.0)
        if isinstance(self.last_val, (tuple, list)):
            self.last_val = self.rng.uniform(self.last_val[0], self.last_val[1])

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        if self.replay is not None and timestep in self.replay.index:
            self.last_val = self.replay[timestep]
            return self.last_val
        if cur_val is None:
            raise ValueError(
                "provided cur_val is None and no replay data is available, but for 'control_from_actions' "
                "generator, one of both has to be provided as source for the current action value"
            )
        if np.isnan(cur_val):
            cur_val = 0.0
        self.last_val += cur_val
        return float(self.last_val)


class differences(ChannelGenerator):
    """
    Provided data generated from some other module, take the differences between the current value and
    the previous value of that channel.

    This is useful, to obtain actions (changes, i.e. differences, of control values) if originally the control values
    themselves are generated.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.last_val = np.nan

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        if self.replay is not None and timestep in self.replay.index:
            self.last_val = cur_val
            return float(self.replay[timestep])
        if cur_val is None or np.isnan(cur_val):
            return 0.0
        previous_val = self.last_val
        self.last_val = cur_val
        return cur_val - previous_val


class spike_action_gen(ChannelGenerator):
    """
    Generate a time series with sparse actions (mostly on the configured offset value).

    There will be at most an action every `stepslen` timesteps; whether there is an action at such a timestep is decided
    randomly according to the `action_prob` probability. If there is an action, it is sampled from the specified `dist`
    distribution, with the `scale` and `offset` parameters.

    In the `action_spec` structure of the config file, each of the parameters below must be prefixed with a "sag_",
    to allow same argument names for different generators.

    Args:
        stepslen: there will be at most an action every `stepslen` timesteps
        action_prob: whether there is an action after `stepslen` timesteps is decided randomly according to the
            `action_prob` probability (in the range [0, 1])
        dist: random value distribution to use for value generation; this can be either "uniform" or "normal".
        scale: generated values follow the distribution provided in the `dist` argement, but are multiplied by `scale`
            during generation.
        offset: the scaled random distribution is shifted by this specified offset
        limits: optional two-element sequence; generated action values are clipped to this interval
    """

    def __init__(
        self,
        stepslen: Optional[int] = None,
        action_prob: Optional[float] = None,
        dist: Optional[str] = None,
        scale: Optional[float] = None,
        offset: Optional[float] = None,
        limits: Optional[Sequence[float]] = None,
        *args,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)
        self.stepslen = stepslen if stepslen is not None else self.spec.get("sag_stepslen", 1)
        self.action_prob = action_prob if action_prob is not None else self.spec.get("sag_action_prob", 1.0)
        self.dist = dist if dist is not None else self.spec.get("sag_dist", "normal")
        self.scale = scale if scale is not None else self.spec.get("sag_scale", 1.0)
        self.offset = offset if offset is not None else self.spec.get("sag_offset", 0.0)
        self.limits = limits if limits is not None else self.spec.get("sag_limits")
        self.steps_until_action = self.stepslen

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        self.steps_until_action -= 1
        if self.steps_until_action == 0:
            self.steps_until_action = self.stepslen
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        if self.steps_until_action < self.stepslen:
            return self.offset
        if self.rng.uniform() >= self.action_prob:
            return self.offset
        new_val = None
        if self.dist == "uniform":
            new_val = self.rng.uniform(low=-self.scale, high=self.scale)
        elif self.dist == "normal":
            new_val = self.rng.normal(loc=0.0, scale=self.scale)
        else:
            raise ValueError(f"Unknown dist '{self.dist}'")
        new_val += self.offset
        if cur_val is not None and not np.isnan(cur_val):
            new_val += cur_val
        if self.limits is not None:
            new_val = float(np.clip(new_val, self.limits[0], self.limits[1]))
        return new_val

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += (
                f"_len={self.stepslen}_prob={self.action_prob:.1f}_dist={self.dist}_"
                f"offset={self.offset:.1f}_scale={self.scale:.2f}"
            )
        return res


class controls_exponential_action_scaler(ChannelGenerator):
    """
    Exponentially transform the raw action values generated by generator modules earlier in the chain.

    The transformation is performed on aggregated actions (or, equivalently, on the inversely transformed associated
    control channel values), and thus makes resulting transformed action values have a larger scale for higher control
    channel values, and smaller scale for smaller control channel values, i.e. makes them more or less proportional to
    the current value of the corresponding control channel.

    The location and scaling of this exponential transform can be configured using `offset` and `factor`. Furthermore,
    it is possible to specify a decay towards the configured `offset` value to avoid diverging too much, and a clipping
    of the actions can be configured using `limits` to keep the associated control channel within the specified
    limits.

    In the `action_spec` structure of the config file, each of the parameters below must be prefixed with a "ceas_",
    to allow same argument names for different generators.

    Args:
        assoc_ctrl_channel: which is the control channel (in process_spec) for which the actions should be generated?
        decay: by which factor should the cumulated generated raw steps be decayed (only if current step != 0.0 at all)
        offset: offset term of the unscaled raw control values before taking exponential (to which value to decay)
        factor: scaling of offsetted raw control values before taking the exponential
        ctrl_limits: clipping of action such that generated transformed control channel values are in these limits
    """

    def __init__(
        self,
        assoc_ctrl_channel: Optional[str] = None,
        decay: Optional[float] = None,
        offset: Optional[float] = None,
        factor: Optional[float] = None,
        ctrl_limits: Optional[Sequence[float]] = None,
        *args,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)
        self.assoc_ctrl_channel = (
            assoc_ctrl_channel if assoc_ctrl_channel is not None else self.spec["ceas_assoc_ctrl_channel"]
        )
        self.decay = decay if decay is not None else self.spec.get("ceas_decay", 0.0)
        self.offset = offset if offset is not None else self.spec.get("ceas_offset", 0.0)
        self.factor = factor if factor is not None else self.spec.get("ceas_factor", 1.0)
        self.ctrl_limits = (
            ctrl_limits if ctrl_limits is not None else self.spec.get("ceas_ctrl_limits", [-np.inf, np.inf])
        )

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        if cur_val == 0.0:
            return 0.0
        current_control = history[self.assoc_ctrl_channel].iloc[-1]
        current_unscaled_control = np.log(current_control) / self.factor
        new_unscaled_control = current_unscaled_control + cur_val
        if self.decay is not None and self.decay != 0.0:
            new_unscaled_control = new_unscaled_control - self.decay * (new_unscaled_control - self.offset)
        new_transformed_control = np.exp(self.factor * new_unscaled_control)
        new_transformed_control = np.clip(new_transformed_control, self.ctrl_limits[0], self.ctrl_limits[1])
        new_transformed_action = new_transformed_control - current_control
        return new_transformed_action

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += (
                f"_ctrl={self.assoc_ctrl_channel}_decay={self.decay:.1f}_offset={self.offset:.1f}_"
                f"factor={self.factor:.1f}"
            )
        return res


class controls_limiter(ChannelGenerator):
    """
    Make controls resulting from generated action stay in configured limits, and decay towords configured `mean`.

    In the `action_spec` structure of the config file, each of the parameters below must be prefixed with a "cd_",
    to allow same argument names for different generators.

    Args:
        assoc_ctrl_channel: which is the control channel (in process_spec) for which the actions should be generated?
        decay: by which factor should the cumulated generated steps be decayed (only if current step != 0.0 at all)
        offset: to which value should the resulting control value decay
        ctrl_limits: clipping of action such that resulting control channel values are in these limits
    """

    def __init__(
        self,
        assoc_ctrl_channel: Optional[str] = None,
        decay: Optional[float] = None,
        offset: Optional[float] = None,
        ctrl_limits: Optional[Sequence[float]] = None,
        *args,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)
        self.assoc_ctrl_channel = (
            assoc_ctrl_channel if assoc_ctrl_channel is not None else self.spec["cl_assoc_ctrl_channel"]
        )
        self.decay = decay if decay is not None else self.spec.get("cl_decay", 0.0)
        self.offset = offset if offset is not None else self.spec.get("cl_offset", 0.0)
        self.ctrl_limits = (
            ctrl_limits if ctrl_limits is not None else self.spec.get("cl_ctrl_limits", [-np.inf, np.inf])
        )

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        if cur_val == 0.0:
            return 0.0
        current_control = history[self.assoc_ctrl_channel].iloc[-1]
        new_control = current_control + cur_val
        if self.decay is not None and self.decay != 0.0:
            new_control = new_control - self.decay * (new_control - self.offset)
        new_control = np.clip(new_control, self.ctrl_limits[0], self.ctrl_limits[1])
        new_action = new_control - current_control
        return new_action

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += f"_ctrl={self.assoc_ctrl_channel}_decay={self.decay:.1f}_offset={self.offset:.1f}"
        return res


class random_walk(ChannelGenerator):
    """
    Generate a random-walk-type sequence of artificial data.

    As a first step, random numbers according to `dist` are generated, which are then added to the previously generated
    value to obtain a random-walk sequence of numbers by successive calls of `step()`. If configured (not equal to 0),
    each value is reduced by the `decay` fraction of its value, to keep the sequence from diverging too far from 0.
    In the `process_spec` structure of the config file, each of the parameters below must be prefixed with a "rw_",
    to allow same argument names for different generators.
    If `step` is called with `cur_val` != None, the random walk value is added to the `cur_val` and return as new value.

    Args:
        scale: generated values follow the distribution provided in the `dist` argement, but are multiplied by `scale`
            during generation.
        dist: random value distribution to use for value generation; this can be either "uniform" or "normal".
        decay: if, each value is multiplied by `decay` and subtracted from itself
            and from all its successors. This is inteded to allow ensuring the random walk staying around 0.
    """

    def __init__(
        self,
        scale: Optional[float] = None,
        dist: Optional[str] = None,
        decay: Optional[float] = None,
        spec: Optional[Mapping[str, Any]] = None,
        *args,
        **kwargs,
    ):
        super().__init__(*args, spec=spec, **kwargs)
        self.scale = scale if scale is not None else self.spec.get("rw_scale", 1.0)
        self.dist = dist if dist is not None else self.spec.get("rw_dist", "normal")
        self.decay = decay if decay is not None else self.spec.get("rw_decay", 0.0)
        self.last_val = 0.0

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        if self.replay is not None and timestep in self.replay.index:
            self.last_val = self.replay[timestep]
            return self.last_val
        if self.dist == "uniform":
            new_val = self.rng.uniform(low=-self.scale, high=self.scale)
        elif self.dist == "normal":
            new_val = self.rng.normal(loc=0.0, scale=self.scale)
        else:
            raise ValueError(f"Unknown dist '{self.dist}'")
        new_val += self.last_val
        if self.decay > 0.0:
            new_val -= self.decay * new_val
        self.last_val = new_val
        if cur_val is not None:
            new_val += cur_val
        return new_val

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += f"_scale={self.scale:.1f}_dist={self.dist}_decay={self.decay:.1f}"
        return res


class random_walk_overlay(ChannelGenerator):
    """
    Generate an overlay (element-wise sum) of several `random_walk`-type sequences of artificial data.

    Using `random_walk()`, several of such random walks are overlaid (summed up elementwise) to form a random walk with
    (e.g.) frequent smaller and infrequent larger steps.
    In the `process_spec` structure of the config file, each of the parameters below must be prefixed with a "rwo_",
    to allow same argument names for different generators.
    If `step` is called with `cur_val` != None, the random walk value is added to the `cur_val` and return as new value.

    Args:
        offset: value around which the random walks will vary (shifting them away from 0.0).
        steplen: sequence of int/None (latter will be interpreted as 1) with one element per random walk; these are the
            number of steps the respective random walk should stay constant before the next value is generated; using
            this parameter, random walks with changes on different time scales/step intervals can be generated, e.g.
            some with low variance but changing every step, while others have larger scales but change only every
            so often.
        scales: scale of the respective random walk (see `random_walk`); if a scalar is provided it will be used for
            every random walk.
        decays: decay of the respective random walk (see `random_walk`); if a scalar is provided it will be used for
            every random walk.
        dists: the random distribution ("uniform", "normal") of the respective random walk (see `random_walk`);
            if a scalar is provided it will be used for every random walk.
    """

    def __init__(
        self,
        offset: Optional[float] = None,
        steplen: Optional[Sequence[Optional[int]]] = None,
        scales: Optional[Union[Sequence[float], float]] = None,
        dists: Optional[Union[Sequence[str], str]] = None,
        decays: Optional[Union[Sequence[float], float]] = None,
        *args,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)
        steplen_raw = steplen if steplen is not None else self.spec.get("rwo_steplen", [None])
        scales = scales if scales is not None else self.spec.get("rwo_scales", [1])
        dists = dists if dists is not None else self.spec.get("rwo_dists", ["normal"])
        decays = decays if decays is not None else self.spec.get("rwo_decays", [0.0])
        if offset is None:
            offset = self.spec.get("rwo_offset", self.spec.get("offset", 0.0))
        self.offset = offset
        steplen_seq = cast(Sequence[Optional[int]], steplen_raw)
        self.steplen = [sl if sl is not None else 1 for sl in steplen_seq]
        self.scales = (
            cast(Sequence[float], scales) if is_sequence(scales) else [cast(float, scales)] * len(self.steplen)
        )
        self.decays = (
            cast(Sequence[float], decays) if is_sequence(decays) else [cast(float, decays)] * len(self.steplen)
        )
        self.dists = cast(Sequence[str], dists) if is_sequence(dists) else [cast(str, dists)] * len(self.steplen)
        self.step_counts = [sl for sl in self.steplen]
        self.last_vals: List[float] = [0.0] * len(self.steplen)
        self.random_walks = [
            random_walk(scale=scale, dist=dist, decay=decay, channel_name=self.channel_name, rng=self.rng)
            for scale, dist, decay in zip(self.scales, self.dists, self.decays)
        ]

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        walk = self.offset
        for i, rand_walk in enumerate(self.random_walks):
            if self.step_counts[i] >= self.steplen[i]:
                self.last_vals[i] = rand_walk.step(timestep, history, cur_val)
                self.step_counts[i] = 0
            walk += self.last_vals[i]
            self.step_counts[i] += 1
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        if cur_val is not None:
            walk += cur_val
        return walk

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += f"_offset={self.offset:.1f}"
        return res


class white_noise(ChannelGenerator):
    """
    Generate an iid sequence of artificial data.

    Random numbers are generated according to `dist`, with their default value range multiplied by `scale`.
    If `step` is called with `cur_val` != None, the noise value is added to the `cur_val` and return as new value.
    In the `process_spec` structure of the config file, each of the parameters below must be prefixed with a "wn_",
    to allow same argument names for different generators.

    Args:
        scale: enerated values follow the distribution provided in the `dist` argement, but are multiplied by `scale`
            during generation.
        dist: random value distribution to use for value generation; this can be either "uniform" or "normal".
    """

    def __init__(self, scale: Optional[float] = None, dist: Optional[str] = None, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.scale = scale if scale is not None else self.spec.get("wn_scale", 1.0)
        self.dist = dist if dist is not None else self.spec.get("wn_dist", "normal")

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        if self.dist == "uniform":
            new_val = self.rng.uniform(low=-self.scale, high=self.scale)
        elif self.dist == "normal":
            new_val = self.rng.normal(loc=0.0, scale=self.scale)
        else:
            raise ValueError(f"Unknown dist '{self.dist}'")
        if cur_val is not None:
            new_val += cur_val
        return new_val

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += f"_scale={self.scale:.1f}_dist={self.dist}"
        return res


class function_callback(ChannelGenerator):
    """
    Transform this generated series or one/multiple named channels by some transformation function.
    In the `process_spec` structure of the config file, each of the parameters below must be prefixed with a "fc_",
    to allow same argument names for different generators.

    Args:
        inputs: Names of the series (from `history`) to be provided as input to the callback function `callback`.
        callback: Function to be called for the configured series'. It should accept a float (the output of the
            previous generator in the chain for the current channel, but only if this is not the first generator in
            the chain) and/or one or several sequences as input (depending on the `inputs` argument), and return a new
            value.
    """

    def __init__(self, inputs: Optional[Sequence[str]] = None, callback: Optional[Callable] = None, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.inputs = inputs if inputs is not None else self.spec.get("fc_inputs", [])
        self.callback = callback if callback is not None else self.spec["fc_callback"]
        self.input_values = pd.Series(
            [], index=pd.DatetimeIndex([], tz="utc"), dtype=np.float32, name=f"{self.channel_name}_fc_input"
        )

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: Optional[float] = None) -> float:
        self.input_values.loc[timestep] = np.nan if cur_val is None else cur_val  # type: ignore[index,assignment]
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        try:
            new_val = self.callback(
                *(
                    ([self.input_values] if cur_val is not None else [])
                    + [self.input_values.index if inp == "index" else history[inp] for inp in self.inputs]
                )
            )
        except (RuntimeError, IndexError) as e:
            logger.debug("callback function evaluation resulted in exception: %s", e)
            new_val = np.nan
        return new_val

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += f"_inputs={','.join(self.inputs)}"
        return res


class lagged_terms(ChannelGenerator):
    """
    Compute a sum of products of (lagged) channel values, i.e. a polynomial of the inputs without code strings.

    The value is `sum(term["coef"] * prod(factor values))` over all terms. A factor is a mapping with the keys
    `input` (name of a channel in `history`), `lag` (number of timesteps, default 0, i.e. the current value of a channel
    computed before this one), `scale` (default 1.0), `offset` (default 0.0) and `power` (non-zero integer or float,
    default 1), with the value `(offset + scale * x[t - lag]) ** power`. A negative power divides by the factor.
    Instead of `lag`, a factor can contain `transport`, a mapping with the keys `speed` (name of a channel computed
    before this one), `distance`, `speed_scale` (default 1.0), `min_lag` (default 1) and `max_lag`: the lag is then the
    smallest number of timesteps k for which the transported distance `sum(speed_scale * speed[t - j] * dt for j < k)`
    reaches `distance` (`dt` being the timestep duration in seconds), clipped to `[min_lag, max_lag]`. This models a
    variable transport delay between an actuator and a sensor (plug flow).
    If the history of an input is too short for a lag, the result is NaN. If this is not the first generator in the
    chain, the result is added to `cur_val`.
    In the `process_spec` structure of the config file, each of the parameters below must be prefixed with a "lt_",
    to allow same argument names for different generators.

    Args:
        terms: Sequence of terms, each a mapping with `coef` (default 1.0) and `factors` (sequence of factors as
            described above), e.g. `[{coef: 1.5, factors: [{input: BP, lag: 3}, {input: DS, lag: 1, power: -1}]}]`
            for `1.5 * BP[t-3] / DS[t-1]`.
    """

    def __init__(self, terms: Optional[Sequence[Mapping[str, Any]]] = None, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.terms = terms if terms is not None else self.spec["lt_terms"]

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: Optional[float] = None) -> float:
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        new_val = 0.0
        for term in self.terms:
            value = float(term.get("coef", 1.0))
            for factor in term.get("factors", []):
                x = self._factor_value(factor, timestep, history)
                if x is None:
                    return np.nan
                power = factor.get("power", 1)
                if power > 0:
                    value *= x if power == 1 else x**power
                else:
                    value /= x if power == -1 else x ** (-power)
            new_val += value
        if cur_val is not None:
            new_val = cur_val + new_val
        return new_val

    def _factor_value(
        self, factor: Mapping[str, Any], timestep: dt.datetime, history: Mapping[str, pd.Series]
    ) -> Optional[float]:
        """Return `offset + scale * x[t - lag]` of a factor, or None if the history is too short."""
        lag = (
            self._transport_lag(factor["transport"], timestep, history)
            if "transport" in factor
            else factor.get("lag", 0)
        )
        if lag is None:
            return None
        x = _lagged_value(history[factor["input"]], timestep, lag)
        if x is None:
            return None
        scale = factor.get("scale", 1.0)
        offset = factor.get("offset", 0.0)
        if scale != 1.0:
            x = scale * x
        if offset != 0.0:
            x = offset + x
        return x

    @staticmethod
    def _transport_lag(
        transport: Mapping[str, Any], timestep: dt.datetime, history: Mapping[str, pd.Series]
    ) -> Optional[int]:
        """Return the transport delay in timesteps, or None if the history is too short."""
        speed = history[transport["speed"]]
        if len(speed) < 2:
            return None
        step_seconds = (speed.index[-1] - speed.index[-2]).total_seconds()
        speed_scale = transport.get("speed_scale", 1.0)
        min_lag = transport.get("min_lag", 1)
        max_lag = transport["max_lag"]
        target = transport["distance"] * (1.0 - 1e-9)
        distance = 0.0
        lag = max_lag
        for k in range(1, max_lag + 1):
            v = _lagged_value(speed, timestep, k - 1)
            if v is None:
                return None
            distance += speed_scale * v * step_seconds
            if distance >= target:
                lag = k
                break
        return max(lag, min_lag)

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            factors = [
                f"{f['input']}@{'v' if 'transport' in f else f.get('lag', 0)}"
                for term in self.terms
                for f in term.get("factors", [])
            ]
            res += f"_inputs={','.join(factors)}"
        return res


def _lagged_value(series: pd.Series, timestep: dt.datetime, lag: int) -> Optional[float]:
    """
    Return the value of a channel history `lag` timesteps before `timestep`, or None if the history is too short.

    The history contains the value of the current timestep only if its channel has already been computed for it.

    Raises:
        ValueError: if `lag` is 0 and the value of the current timestep has not been computed yet.
    """
    n = len(series)
    current = n > 0 and series.index[-1] == timestep
    pos = n - 1 - lag if current else n - lag
    if pos >= n:
        raise ValueError(f"lag 0 of channel {series.name} requested before its value for {timestep} was computed")
    return series.values[pos] if pos >= 0 else None


class modulated_sine(ChannelGenerator):
    """
    Generate a sine wave whose amplitude is modulated exponentially by the current value of another channel.

    The value is `amplitude * exp(exp_scale * x + exp_offset) * sin(angular_frequency * s + phase)`, with x the most
    recent value of the channel `input` (a constant envelope `amplitude * exp(exp_offset)` without input) and s the
    seconds since the first step of this generator (including warm-up steps). If this is not the first generator in
    the chain, the result is added to `cur_val`.
    In the `process_spec` structure of the config file, each of the parameters below must be prefixed with a "ms_",
    to allow same argument names for different generators.

    Args:
        input: Name of the channel (from `history`) modulating the amplitude.
        amplitude: Amplitude factor of the wave.
        exp_scale: Factor of the input value in the exponent.
        exp_offset: Offset of the exponent.
        angular_frequency: Angular frequency of the wave in rad/s.
        phase: Phase of the wave in rad.
    """

    def __init__(
        self,
        input: Optional[str] = None,  # pylint: disable=redefined-builtin
        amplitude: Optional[float] = None,
        exp_scale: Optional[float] = None,
        exp_offset: Optional[float] = None,
        angular_frequency: Optional[float] = None,
        phase: Optional[float] = None,
        *args,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)
        self.input = input if input is not None else self.spec.get("ms_input")
        self.amplitude = amplitude if amplitude is not None else self.spec.get("ms_amplitude", 1.0)
        self.exp_scale = exp_scale if exp_scale is not None else self.spec.get("ms_exp_scale", 0.0)
        self.exp_offset = exp_offset if exp_offset is not None else self.spec.get("ms_exp_offset", 0.0)
        self.angular_frequency = (
            angular_frequency if angular_frequency is not None else self.spec.get("ms_angular_frequency", 1.0)
        )
        self.phase = phase if phase is not None else self.spec.get("ms_phase", 0.0)
        self.first_timestep: Optional[dt.datetime] = None

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: Optional[float] = None) -> float:
        if self.first_timestep is None:
            self.first_timestep = timestep
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        x = 0.0
        if self.input is not None:
            values = history[self.input]
            if len(values) == 0:
                return np.nan
            x = values.values[-1]
        seconds = (pd.Timestamp(timestep) - pd.Timestamp(self.first_timestep)).total_seconds()
        new_val = (
            self.amplitude
            * np.exp(self.exp_scale * x + self.exp_offset)
            * np.sin(self.angular_frequency * seconds + self.phase)
        )
        if cur_val is not None:
            new_val = cur_val + new_val
        return new_val

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += f"_input={self.input}"
        return res


class apply_filter(ChannelGenerator):
    """
    Apply a FIR filter `kernel` to the current series, returning the current value for the filter.
    In the `process_spec` structure of the config file, each of the parameters below must be prefixed with a "af_",
    to allow same argument names for different generators.

    Args:
        kernel: FIR filter to apply, as a sequence of floats. This is handed over to scipy.signal.convolve(); the first
            element of the filter corresponds to the most recent time step, while later elements of the filter are
            multiplied with earlier time series elements.
            In the YAML config file, a python snippet calculating and returning a filter as sequence of floats can also
            be specified (e.g. `norm_filter(scipy.signal.windows.hann(150))`).
        window: Alternative to `kernel` without code: mapping with `name` (see `functions.WINDOW_NAMES`), `length` and
            optional `normalize` (default True), e.g. `{name: hann, length: 150}`, see `functions.window_filter`.
    """

    def __init__(
        self, kernel: Optional[Sequence[float]] = None, window: Optional[Mapping[str, Any]] = None, *args, **kwargs
    ):
        super().__init__(*args, **kwargs)
        if kernel is None:
            window = window if window is not None else self.spec.get("af_window")
            kernel = cast(Sequence[float], window_filter(**window) if window is not None else self.spec["af_kernel"])
        self.kernel: Sequence[float] = kernel
        self.input_values = pd.Series(
            [], index=pd.DatetimeIndex([], tz="utc"), dtype=np.float32, name=f"{self.channel_name}_fc_input"
        )
        self.kernel_size = len(self.kernel)
        self.filter_delay = 0
        for i, elem in enumerate(self.kernel):
            if elem == 0:
                self.filter_delay = i + 1
            else:
                break

    def step(self, timestep: dt.datetime, history: Mapping[str, pd.Series], cur_val: float = np.nan) -> float:
        if not np.isnan(cur_val):
            self.input_values.loc[timestep] = cur_val  # type: ignore[index,assignment]
            timeseries = self.input_values.values
            if timeseries.shape[0] < len(self.kernel):
                timeseries = np.pad(timeseries, pad_width=((len(self.kernel) - timeseries.shape[0], 0),), mode="edge")  # type: ignore[arg-type]
            try:
                new_val = signal.convolve(timeseries[-self.kernel_size :], self.kernel, mode="valid")[0]
            except ValueError as e:
                raise ValueError(
                    f"convolution failed for cur_val={cur_val}, "
                    f"with timeseries={str(timeseries[-self.kernel_size :])} and "
                    f"kernel={str(self.kernel)}"
                ) from e
        else:
            self.input_values = pd.Series(
                [], index=pd.DatetimeIndex([], tz="utc"), dtype=np.float32, name=f"{self.channel_name}_fc_input"
            )
            new_val = cur_val
        if self.replay is not None and timestep in self.replay.index:
            return self.replay[timestep]
        return new_val

    def info_str(self, verbosity=1):
        res = super().info_str(verbosity)
        if verbosity >= 1:
            res += f"_delay={self.filter_delay}..{self.kernel_size}"
        return res


def get_num_plots(spec: Mapping[str, Mapping[str, Any]], with_intermediates=False, with_temporaries=False) -> int:
    """
    From the given spec, determine the number of plots to be generated.

    There will be one for each feature specification, plus one for each temporary series generated in the process of
    building it.

    Args:
        spec: A data generation specification as used for `gen_data`.
        with_intermediates: Also plot (indented) series generated by generators not being the last in the `type` list of
          process specs.
        with_temporaries: Also plot temporary series usually not persisted, but only used for computation of other
          series.

    Returns:
        number of plots resulting from given feature `spec`.
    """
    num_plots = 0
    for _, sub_spec in spec.items():
        if sub_spec["semantics"] in ("temp",) and not with_temporaries:
            continue
        num_plots += 1
        if with_intermediates and isinstance(sub_spec["type"], (list, tuple)):
            num_plots += len(sub_spec["type"]) - 1
    return num_plots


def short_class_name(s):
    elements = s.split("_")
    return "".join([el[0].lower() if len(el) > 0 else "" for el in elements])
